"""M3 tables. Enums are strings with CHECK constraints so the schema is identical on SQLite and
PostgreSQL. IDs are UUID strings generated by the API. All timestamps are UTC."""

import uuid
from datetime import datetime

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Float,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    String,
)
from sqlalchemy.orm import Mapped, deferred, mapped_column, relationship

from app.db import Base, UTCDateTime, utc_now
from app.domain.incident_rules import (
    CAMERA_STATUSES,
    DETECTION_EVENT_TYPES,
    INCIDENT_STATUSES,
    REVIEW_STATUSES,
    SEVERITIES,
    STATION_STATUSES,
    TIMELINE_ACTORS,
    TIMELINE_EVENT_TYPES,
)

# Karachi bounding box (Schema.md §1): enforces the Karachi-only scope at the data layer.
LAT_MIN, LAT_MAX, LNG_MIN, LNG_MAX = 24.70, 25.30, 66.60, 67.60


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


def _karachi(prefix: str) -> CheckConstraint:
    return CheckConstraint(
        f"latitude BETWEEN {LAT_MIN} AND {LAT_MAX} AND longitude BETWEEN {LNG_MIN} AND {LNG_MAX}",
        name=f"ck_{prefix}_karachi_bbox",
    )


def new_id() -> str:
    return str(uuid.uuid4())


class Camera(Base):
    __tablename__ = "camera"
    __table_args__ = (
        CheckConstraint(_in("status", CAMERA_STATUSES), name="ck_camera_status"),
        _karachi("camera"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    code: Mapped[str] = mapped_column(String(20), unique=True)
    name: Mapped[str] = mapped_column(String(120))
    latitude: Mapped[float] = mapped_column(Float)
    longitude: Mapped[float] = mapped_column(Float)
    location_label: Mapped[str] = mapped_column(String(160))
    department: Mapped[str] = mapped_column(String(20), default="fire")
    status: Mapped[str] = mapped_column(String(20), default="active")
    is_simulated: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now, onupdate=utc_now)


class FireStation(Base):
    __tablename__ = "fire_station"
    __table_args__ = (
        CheckConstraint(_in("status", STATION_STATUSES), name="ck_fire_station_status"),
        CheckConstraint(
            _in("verification_status", ("unverified", "verified")),
            name="ck_fire_station_verification",
        ),
        _karachi("fire_station"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    code: Mapped[str] = mapped_column(String(20), unique=True)
    name: Mapped[str] = mapped_column(String(160))
    latitude: Mapped[float] = mapped_column(Float)
    longitude: Mapped[float] = mapped_column(Float)
    location_label: Mapped[str] = mapped_column(String(300))
    # Demo toggle only, never a claim about real-world availability.
    status: Mapped[str] = mapped_column(String(20), default="available")
    is_simulated: Mapped[bool] = mapped_column(Boolean, default=False)
    data_source: Mapped[str] = mapped_column(String(20))  # osm | manual_demo
    source_ref: Mapped[str | None] = mapped_column(String(200))
    licence: Mapped[str | None] = mapped_column(String(50))
    verification_status: Mapped[str] = mapped_column(String(20), default="unverified")
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now, onupdate=utc_now)


class DetectionEvent(Base):
    __tablename__ = "detection_event"
    __table_args__ = (
        CheckConstraint(_in("event_type", DETECTION_EVENT_TYPES), name="ck_detection_event_type"),
        CheckConstraint(_in("review_status", REVIEW_STATUSES), name="ck_detection_review_status"),
        CheckConstraint("confidence >= 0 AND confidence <= 1", name="ck_detection_confidence"),
        Index("ix_detection_review_created", "review_status", "created_at"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    camera_id: Mapped[str] = mapped_column(ForeignKey("camera.id"), index=True)
    event_type: Mapped[str] = mapped_column(String(20))
    confidence: Mapped[float] = mapped_column(Float)
    evidence_timestamp_s: Mapped[float | None] = mapped_column(Float)
    # Annotated evidence JPEG (~25 KB). Deferred so list queries never load the bytes.
    evidence_jpeg: Mapped[bytes | None] = deferred(mapped_column(LargeBinary))
    detected_at: Mapped[datetime] = mapped_column(UTCDateTime)
    model: Mapped[str] = mapped_column(String(80))
    threshold: Mapped[float] = mapped_column(Float)
    # Per-class verdicts, boxes, frame counts and timing from the detector response.
    details: Mapped[dict] = mapped_column(JSON, default=dict)
    review_status: Mapped[str] = mapped_column(String(20), default="pending")
    reviewed_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    reviewed_by: Mapped[str | None] = mapped_column(String(80))
    review_note: Mapped[str | None] = mapped_column(String(1000))
    is_simulated: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)

    camera: Mapped[Camera] = relationship()


class Incident(Base):
    __tablename__ = "incident"
    __table_args__ = (
        CheckConstraint(_in("status", INCIDENT_STATUSES), name="ck_incident_status"),
        CheckConstraint(_in("severity", SEVERITIES), name="ck_incident_severity"),
        CheckConstraint(_in("event_type", DETECTION_EVENT_TYPES), name="ck_incident_event_type"),
        _karachi("incident"),
        Index("ix_incident_status_created", "status", "created_at"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    camera_id: Mapped[str] = mapped_column(ForeignKey("camera.id"), index=True)
    # UNIQUE: one incident per detection, the database-level guard against double confirmation.
    detection_event_id: Mapped[str] = mapped_column(ForeignKey("detection_event.id"), unique=True)
    event_type: Mapped[str] = mapped_column(String(20))
    severity: Mapped[str] = mapped_column(String(10))
    status: Mapped[str] = mapped_column(String(20))
    latitude: Mapped[float] = mapped_column(Float)
    longitude: Mapped[float] = mapped_column(Float)
    assigned_station_id: Mapped[str | None] = mapped_column(ForeignKey("fire_station.id"))
    station_distance_km: Mapped[float | None] = mapped_column(Float)
    confirmed_by: Mapped[str | None] = mapped_column(String(80))
    confirmed_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    resolved_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    is_simulated: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)
    updated_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now, onupdate=utc_now)

    camera: Mapped[Camera] = relationship()
    detection: Mapped[DetectionEvent] = relationship()
    station: Mapped[FireStation | None] = relationship()
    timeline: Mapped[list["IncidentTimelineEvent"]] = relationship(
        order_by="IncidentTimelineEvent.seq", back_populates="incident"
    )


class IncidentTimelineEvent(Base):
    """Append-only. `seq` orders events within an incident (timestamps can tie or be backdated)."""

    __tablename__ = "incident_timeline_event"
    __table_args__ = (
        CheckConstraint(_in("event_type", TIMELINE_EVENT_TYPES), name="ck_timeline_event_type"),
        CheckConstraint(_in("actor", TIMELINE_ACTORS), name="ck_timeline_actor"),
        Index("ux_timeline_incident_seq", "incident_id", "seq", unique=True),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=new_id)
    incident_id: Mapped[str] = mapped_column(ForeignKey("incident.id"))
    seq: Mapped[int] = mapped_column(Integer)
    event_type: Mapped[str] = mapped_column(String(30))
    actor: Mapped[str] = mapped_column(String(20))
    actor_label: Mapped[str | None] = mapped_column(String(80))
    message: Mapped[str] = mapped_column(String(500))
    details: Mapped[dict] = mapped_column(JSON, default=dict)
    occurred_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utc_now)

    incident: Mapped[Incident] = relationship(back_populates="timeline")
